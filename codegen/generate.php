<?php

/**
 * Generates service, factory and resource classes from codegen/spec.json.
 *
 * Usage: php codegen/generate.php
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$spec = json_decode((string) file_get_contents(__DIR__ . '/spec.json'), true, 512, JSON_THROW_ON_ERROR);

const NS = 'WPZinc\\Airwallex';

// Namespace => [property, factory class, description]
$namespaces = [
    'Accounting' => ['accounting', 'Accounting'],
    'Billing'    => ['billing', 'Billing'],
    'Checkout'   => ['checkout', 'Checkout'],
    'Finance'    => ['finance', 'Finance'],
    'Fx'         => ['fx', 'Transactional FX'],
    'Issuing'    => ['issuing', 'Issuing'],
    'Payments'   => ['payments', 'Payment Acceptance (additional resources)'],
    'Risk'       => ['risk', 'Risk'],
    'Scale'      => ['scale', 'Embedded Finance (Scale)'],
    'Simulation' => ['simulation', 'Simulation (sandbox only)'],
];

$generated = [];

// Remove previously generated files so renamed services don't linger.
foreach (['src/Service', 'src/Resource'] as $dir) {
    @mkdir("$root/$dir", 0777, true);
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator("$root/$dir", FilesystemIterator::SKIP_DOTS));
    foreach ($it as $file) {
        if (str_contains((string) file_get_contents((string) $file), '@generated')) {
            unlink((string) $file);
        }
    }
}

$byNamespace = [];
foreach ($spec['services'] as $service) {
    $byNamespace[$service['namespace']][] = $service;
    writeResource($root, $service);
    writeService($root, $service);
}

foreach ($namespaces as $ns => [$prop, $label]) {
    writeFactory($root, $ns, $label, $byNamespace[$ns] ?? [], []);
}

$coreExtra = [];
foreach ($namespaces as $ns => [$prop, $label]) {
    $coreExtra[$prop] = ['class' => NS . "\\Service\\$ns\\{$ns}ServiceFactory", 'label' => $label];
}
$coreExtra['files'] = ['class' => NS . '\\Service\\FileService', 'label' => 'Files'];
writeFactory($root, '', 'Core', $byNamespace[''] ?? [], $coreExtra);

writeServicesDoc($root, $spec['services']);

echo sprintf("Generated %d services, %d methods\n", count($spec['services']), array_sum(array_map(fn ($s) => count($s['methods']), $spec['services'])));

function resourceClass(array $service): string
{
    if ($service['resource'] === null) {
        return NS . '\\AirwallexObject';
    }

    $sub = $service['namespace'] === '' ? '' : $service['namespace'] . '\\';

    return NS . '\\Resource\\' . $sub . $service['resource'];
}

function writeResource(string $root, array $service): void
{
    if ($service['resource'] === null) {
        return;
    }

    $ns   = NS . '\\Resource' . ($service['namespace'] === '' ? '' : '\\' . $service['namespace']);
    $dir  = "$root/src/Resource" . ($service['namespace'] === '' ? '' : '/' . $service['namespace']);
    $name = $service['resource'];

    @mkdir($dir, 0777, true);

    $code = <<<PHP
<?php

declare(strict_types=1);

namespace $ns;

use WPZinc\\Airwallex\\AirwallexObject;

/**
 * @generated by codegen/generate.php
 *
 * @see {$service['doc']}
 *
 * @property string \$id
 */
class $name extends AirwallexObject
{
}

PHP;

    file_put_contents("$dir/$name.php", $code);
}

function writeService(string $root, array $service): void
{
    $ns       = NS . '\\Service' . ($service['namespace'] === '' ? '' : '\\' . $service['namespace']);
    $dir      = "$root/src/Service" . ($service['namespace'] === '' ? '' : '/' . $service['namespace']);
    $class    = $service['class'];
    $resource = resourceClass($service);
    $short    = substr($resource, strrpos($resource, '\\') + 1);

    @mkdir($dir, 0777, true);

    $uses = array_unique([NS . '\\Service\\AbstractService', NS . '\\Collection', $resource]);
    sort($uses);
    $useLines = implode("\n", array_map(fn ($u) => "use $u;", array_filter($uses, fn ($u) => substr($u, 0, strrpos($u, '\\')) !== $ns)));

    $methods = [];
    foreach ($service['methods'] as $m) {
        preg_match_all('/\{([^}]+)\}/', $m['path'], $matches);
        $args = array_map('camelArg', $matches[1]);

        $sig = [];
        $doc = ['     * ' . rtrim($m['summary'], '.') . '.', '     *', '     * ' . $m['http'] . ' ' . $m['path'], '     *'];
        foreach ($args as $arg) {
            $sig[] = "string \$$arg";
            $doc[] = "     * @param string               \$$arg";
        }
        $sig[] = 'array $params = []';
        $sig[] = 'array $opts = []';
        $doc[] = '     * @param array<string, mixed> $params ' . ($m['http'] === 'GET' ? 'Query parameters.' : 'Request body.');
        $doc[] = '     * @param array<string, mixed> $opts   Request options (on_behalf_of, api_version, headers, timeout).';

        $isList  = $m['returns'] === 'collection';
        $returns = $isList ? 'Collection' : $short;
        $doc[]   = $isList ? "     * @return Collection<$short>" : "     * @return $short";

        $path = $args === []
            ? "'" . $m['path'] . "'"
            : "\$this->buildPath('" . $m['path'] . "', \$" . implode(', $', $args) . ')';

        $call      = $isList ? 'requestCollection' : 'request';
        $requestId = in_array($m['request_id'], ['required', 'optional'], true) ? ', true' : '';
        $docBlock  = implode("\n", $doc);
        $sigStr    = implode(', ', $sig);
        $httpLower = strtolower($m['http']);

        $methods[] = <<<PHP
    /**
$docBlock
     */
    public function {$m['name']}($sigStr): $returns
    {
        return \$this->$call('$httpLower', $path, \$params, \$opts, $short::class$requestId);
    }
PHP;
    }

    $body = implode("\n\n", $methods);

    $code = <<<PHP
<?php

declare(strict_types=1);

namespace $ns;

$useLines

/**
 * @generated by codegen/generate.php
 *
 * @see {$service['doc']}
 */
class $class extends AbstractService
{
$body
}

PHP;

    file_put_contents("$dir/$class.php", $code);
}

function writeFactory(string $root, string $namespace, string $label, array $services, array $extra): void
{
    $ns    = NS . '\\Service' . ($namespace === '' ? '' : '\\' . $namespace);
    $dir   = "$root/src/Service" . ($namespace === '' ? '' : '/' . $namespace);
    $class = ($namespace === '' ? 'Core' : $namespace) . 'ServiceFactory';

    $entries = [];
    foreach ($services as $s) {
        $entries[$s['property']] = "$ns\\{$s['class']}";
    }
    foreach ($extra as $prop => $e) {
        $entries[$prop] = $e['class'];
    }
    ksort($entries);

    $props = [];
    $map   = [];
    $width = max(array_map('strlen', array_keys($entries)));
    foreach ($entries as $prop => $fqcn) {
        $short   = substr($fqcn, strrpos($fqcn, '\\') + 1);
        $rel     = str_starts_with($fqcn, $ns . '\\') ? substr($fqcn, strlen($ns) + 1) : '\\' . $fqcn;
        $props[] = " * @property-read $rel \$$prop";
        $map[]   = sprintf("            %-" . ($width + 2) . "s => %s::class,", "'$prop'", $rel);
    }

    $propsStr = implode("\n", $props);
    $mapStr   = implode("\n", $map);
    $useLine  = $namespace === '' ? '' : "\nuse " . NS . "\\Service\\AbstractServiceFactory;\n";

    $code = <<<PHP
<?php

declare(strict_types=1);

namespace $ns;
$useLine
/**
 * $label services.
 *
 * @generated by codegen/generate.php
 *
$propsStr
 */
class $class extends AbstractServiceFactory
{
    protected function serviceClasses(): array
    {
        return [
$mapStr
        ];
    }
}

PHP;

    @mkdir($dir, 0777, true);
    file_put_contents("$dir/$class.php", $code);
}

function camelArg(string $name): string
{
    return lcfirst(str_replace(' ', '', ucwords(str_replace('_', ' ', $name))));
}

function writeServicesDoc(string $root, array $services): void
{
    $out = ["# Services", "", "Every endpoint the SDK wraps, generated from `codegen/spec.json`. Path parameters come first, then `\$params` and `\$opts`.", ""];

    $current = null;
    foreach ($services as $s) {
        $group = $s['namespace'] === '' ? 'Core' : $s['namespace'];
        if ($group !== $current) {
            $out[]   = "## $group";
            $out[]   = '';
            $current = $group;
        }

        $accessor = '$airwallex->' . ($s['namespace'] === '' ? '' : lcfirst($s['namespace']) . '->') . $s['property'];
        $out[]    = "### `$accessor`";
        $out[]    = '';
        $out[]    = "[API reference]({$s['doc']})";
        $out[]    = '';
        $out[]    = '| Method | Endpoint | Description |';
        $out[]    = '| --- | --- | --- |';
        foreach ($s['methods'] as $m) {
            preg_match_all('/\{([^}]+)\}/', $m['path'], $matches);
            $args  = implode(', ', array_map(fn ($a) => '$' . camelArg($a), $matches[1]));
            $out[] = sprintf('| `%s(%s)` | `%s %s` | %s |', $m['name'], $args, $m['http'], $m['path'], rtrim($m['summary'], '.'));
        }
        $out[] = '';
    }

    @mkdir("$root/docs", 0777, true);
    file_put_contents("$root/docs/SERVICES.md", implode("\n", $out));
}
